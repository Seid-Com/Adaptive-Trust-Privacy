"""
Aggregate the supplementary grid results into author-ready replacement text.

Reads (whichever exist):
    data/results/results_ablation.json
    data/results/results_scalability.json
    data/results/results_eps_sweep.json

Writes:
    data/review/measured_scalability_and_eps.md

Safe to re-run at any time; incomplete cells are marked "pending" rather than
guessed. Intended to be run once the grid in run_supp.py finishes.
"""

import json
import statistics as st
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "data" / "results"
OUT = ROOT / "data" / "review" / "measured_scalability_and_eps.md"

SEEDS = [42, 49, 56, 63, 70]
SCAL_SEEDS = [42, 49, 56]


def load(name):
    p = RES / name
    if not p.exists():
        return []
    try:
        return json.load(open(p, encoding="utf-8"))
    except Exception as e:
        print("  [warn] could not parse %s (%s) - mid-write, skipping" % (name, e))
        return []


def ms(vals):
    if not vals:
        return None
    m = 100 * st.mean(vals)
    s = 100 * st.pstdev(vals) if len(vals) > 1 else 0.0
    return m, s, len(vals)


def fmt(vals):
    r = ms(vals)
    if r is None:
        return "pending"
    m, s, n = r
    return "%.2f +/- %.2f (n=%d)" % (m, s, n)


def main():
    scal = load("results_scalability.json")
    eps = load("results_eps_sweep.json")
    abl = load("results_ablation.json")

    L = []
    L.append("# Measured scalability + privacy-utility (author-ready)")
    L.append("")
    L.append("Auto-generated by `scripts/aggregate_supp.py` from the measured grid. "
             "Do not hand-edit the numbers; re-run the script when the grid advances.")
    L.append("")

    # ---- scalability ----
    L.append("## 1. Scalability")
    L.append("")
    g = defaultdict(list)
    for r in scal:
        g[(r["n_clients"], r["method"])].append(r["accuracy"])
    ns = sorted({n for n, _ in g})
    if not ns:
        L.append("_No scalability results yet._")
    else:
        L.append("| N clients | TA-ADP acc (%) | FedAvg+DP acc (%) | TA-ADP - FedAvg+DP (pp) |")
        L.append("|---|---|---|---|")
        for n in ns:
            a = g.get((n, "TA-ADP"), [])
            b = g.get((n, "FedAvg+DP"), [])
            ma = ms(a)
            mb = ms(b)
            delta = ("%+.2f" % (ma[0] - mb[0])) if (ma and mb) else "pending"
            L.append("| %d | %s | %s | %s |" % (n, fmt(a), fmt(b), delta))
        L.append("")
        L.append("Per-round worst-case epsilon by N (TA-ADP):")
        L.append("")
        eg = defaultdict(list)
        for r in scal:
            if r["method"] == "TA-ADP":
                eg[r["n_clients"]].append(r["epsilon"])
        L.append("| N clients | eps | " + " | ".join("seed %d" % s for s in SCAL_SEEDS) + " |")
        L.append("|---|---|" + "---|" * len(SCAL_SEEDS))
        for n in ns:
            byseed = {r["seed"]: r["epsilon"] for r in scal
                      if r["n_clients"] == n and r["method"] == "TA-ADP"}
            L.append("| %d | " % n
                     + " | ".join(("%.2f" % byseed[s]) if s in byseed else "pending"
                                  for s in SCAL_SEEDS) + " |")
    L.append("")

    # ---- eps sweep ----
    L.append("## 2. Privacy-utility sweep")
    L.append("")
    L.append("Prior claimed reference points (unverified): 89.2% at eps=1.0, "
             "86.5% 'Adaptive DP', 84.1% FedAvg+DP at eps=1.0; 91.0% at eps=3.0; "
             "91.5% at eps=5.0.")
    L.append("")
    bym = defaultdict(lambda: defaultdict(list))
    byeps = defaultdict(lambda: defaultdict(list))
    for r in eps:
        t = r.get("target_eps")
        bym[t][r["method"]].append(r["accuracy"])
        byeps[t][r["method"]].append(r["epsilon"])
    ts = sorted(x for x in bym if x is not None)
    if not ts:
        L.append("_No eps-sweep results yet._")
    else:
        methods = ["TA-ADP", "FedAvg+DP", "cosAFed"]
        L.append("Measured eps is per method: each method's actual worst-case "
                 "epsilon differs slightly for the same sigma budget.")
        L.append("")
        L.append("| target eps | " + " | ".join("%s acc (%%) @ eps" % m for m in methods) + " |")
        L.append("|---|" + "---|" * len(methods))
        for t in ts:
            cells = []
            for m in methods:
                accs = bym[t].get(m, [])
                epss = byeps[t].get(m, [])
                if not accs:
                    cells.append("pending")
                    continue
                m_, s_, n_ = ms(accs)
                e_ = ("%.2f" % st.mean(epss)) if epss else "?"
                cells.append("%.2f +/- %.2f @ %s (n=%d)" % (m_, s_, e_, n_))
            L.append("| %.1f | " % t + " | ".join(cells) + " |")
    L.append("")

    # ---- ablation recap ----
    L.append("## 3. Ablation recap (measured, complete)")
    L.append("")
    ga = defaultdict(list)
    for r in abl:
        ga[r.get("variant")].append(r["accuracy"])
    if "full" in ga:
        full = st.mean(ga["full"])
        L.append("| Variant | acc (%) | delta vs full (pp) |")
        L.append("|---|---|---|")
        for v in ["full", "adaptive_sigma_only", "trust_only", "selection_only",
                  "no_trust", "no_resource", "no_adaptive_noise", "no_both"]:
            a = ga.get(v, [])
            if a:
                L.append("| %s | %s | %+.2f |" % (v, fmt(a), 100 * (st.mean(a) - full)))
            else:
                L.append("| %s | pending | - |" % v)
    L.append("")
    L.append("_See the ablation section above for the full narrative._")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote", OUT)
    print("  scalability rows: %d | eps rows: %d | ablation rows: %d" % (len(scal), len(eps), len(abl)))


if __name__ == "__main__":
    main()
